package com.mochyy.mochymusic.lyrics

import android.os.SystemClock
import android.util.LruCache
import com.mochyy.mochymusic.ui.player.findOfficialMusicVideoId
import com.mochyy.mochymusic.utils.OfflineMode
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Deferred
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.async

// a video's own uploaded translation, used as the lyrics translation and timed to the lyrics through the video's other captions
object YouTubeCaptionTranslation {

    class Request(
        val songId: String,
        val title: String,
        val artist: String,
        // the track is the video itself, so no search is needed to find it
        val isVideo: Boolean,
        val lines: List<LyricsEntry>,
        val targetLanguage: String,
    )

    // what a stored youtube translation is filed under, kept apart from google's and the ai's
    fun storedLanguageTag(targetLanguage: String): String = "yt:$targetLanguage"

    private class Found(val lines: List<String?>?, val atMs: Long = SystemClock.elapsedRealtime())

    private val results = LruCache<String, Found>(24)
    private val inFlight = HashMap<String, Deferred<List<String?>?>>()
    // its own scope, so the translate sheet closing doesn't cancel a lookup the lyrics are also waiting on
    private val scope = CoroutineScope(SupervisorJob() + Dispatchers.IO)

    // the translation for each of the request's lines (null where a line has none), or null when youtube has nothing to offer
    suspend fun translate(request: Request): List<String?>? {
        if (OfflineMode.isOn || request.lines.isEmpty() || request.targetLanguage.isBlank()) return null
        val key = keyOf(request)
        results.get(key)?.let { found ->
            // nothing found is asked again after a while, it may only have been a dropped connection
            if (found.lines != null || SystemClock.elapsedRealtime() - found.atMs < MissRetryMs) return found.lines
        }
        val job = synchronized(inFlight) {
            inFlight[key] ?: scope.async {
                try {
                    // a failed lookup only means no youtube translation; the lyrics then translate the usual way
                    runCatching { lookUp(request) }.getOrNull().also { results.put(key, Found(it)) }
                } finally {
                    synchronized(inFlight) { inFlight.remove(key) }
                }
            }.also { inFlight[key] = it }
        }
        return job.await()
    }

    private suspend fun lookUp(request: Request): List<String?>? {
        val videoId = if (request.isVideo) request.songId else findOfficialMusicVideoId(request.title, request.artist)
        val captions = videoId?.let { VideoCaptionSource.captions(it) } ?: return null
        // only a track someone uploaded counts: youtube's own machine translation is no better than google's
        val translationTrack = captions.tracks.firstOrNull {
            !it.isAutoGenerated && VideoCaptionSource.sameLanguage(it.languageCode, request.targetLanguage)
        } ?: return null
        val aligned = VideoCaptionSource.align(captions, request.lines, skipLanguage = request.targetLanguage) ?: return null
        // the song is already in the language asked for, so its captions are the lyrics and not a translation
        if (VideoCaptionSource.sameLanguage(aligned.track.languageCode, request.targetLanguage)) return null
        val translationCues = VideoCaptionSource.cues(captions, translationTrack) ?: return null
        val translated = CaptionAligner.assignCues(request.lines, aligned.alignment.map, translationCues)
        val wanted = request.lines.count { !it.isBackground && it.text.isNotBlank() }
        // half the song left untranslated reads worse than a machine translation of all of it
        return translated.takeIf { lines -> lines.count { it != null } * 2 >= wanted }
    }

    private fun keyOf(request: Request): String {
        val linesHash = request.lines.fold(17) { hash, line -> 31 * hash + (line.time.hashCode() * 31 + line.text.hashCode()) }
        return "${request.songId}|${request.targetLanguage}|$linesHash"
    }

    private const val MissRetryMs = 5 * 60_000L
}
